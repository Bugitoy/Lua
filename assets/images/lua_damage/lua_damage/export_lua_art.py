"""Write luaArt.ts (the pixel grids the procedural renderer draws from) out of make_sheets.py.

make_sheets.py stays the single source of truth for Lua's art: change a grid or a palette there,
then run this again so the app picks it up.

Run:  python3 export_lua_art.py path/to/make_sheets.py path/to/luaArt.ts
"""
import importlib.util
import json
import sys


def load(path):
    spec = importlib.util.spec_from_file_location('make_sheets', path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def grid(t):
    """(rows, x, y) tuple -> {rows, x, y}"""
    return {'rows': t[0], 'x': t[1], 'y': t[2]}


def rgb(c):
    return list(c[:3])


def main(src, dst):
    m = load(src)
    clothes = []
    for it in m.CLOTHES:
        c = {k: it[k] for k in ('id', 'name', 'slot', 'x', 'y', 'rows')}
        for k in ('sleeves', 'hood'):
            if k in it:
                c[k] = it[k]
        clothes.append(c)
    costumes = [{
        'id': c['id'], 'name': c['name'], 'pal': c.get('pal', {}),
        'eyes': c.get('eyes', 'open') is not None,
        'layers': [{'z': z, 'x': x, 'y': y, 'rows': rows} for (z, x, y, rows) in c['layers']],
    } for c in m.COSTUMES]
    data = {
        'PAL': m.PAL,
        'HEAD': m.HEAD,
        'BODY': m.BODY,
        'HAND_L': grid(m.HAND_L),
        'HAND_R': grid(m.HAND_R),
        'EYES': {k: grid(v) for k, v in m.EYES.items()},
        'CLOTHES': clothes,
        'SKINS': [{'id': s['id'], 'name': s['name'], 'pal': s['pal']} for s in m.SKINS],
        'COSTUMES': costumes,
        'FX': {
            'dirt': [rgb(c) for c in m.DIRT],
            'spark': [rgb(c) for c in m.SPARK],
            'smoke': [list(c) for c in m.SMOKE_SHADES],
            'star': rgb(m.STAR),
            'sweat': rgb(m.SWEAT),
            'heal': [rgb(m.hexrgb(m.PAL['G'])), rgb(m.hexrgb(m.PAL['Y']))],
        },
    }
    out = ['// Generated by export_lua_art.py from make_sheets.py. Do not edit by hand.', '']
    types = {
        'PAL': 'Record<string, string>', 'HEAD': 'string[]', 'BODY': 'string[]',
        'HAND_L': 'ArtGrid', 'HAND_R': 'ArtGrid', 'EYES': 'Record<EyeKind, ArtGrid>',
        'CLOTHES': 'ClothingItem[]', 'SKINS': 'PaletteSkin[]', 'COSTUMES': 'Costume[]', 'FX': 'FxColours',
    }
    out.append("export type EyeKind = %s;" % ' | '.join("'%s'" % k for k in m.EYES))
    out.append('export interface ArtGrid { rows: string[]; x: number; y: number }')
    out.append('export interface ClothingItem extends ArtGrid { id: string; name: string; slot: string;')
    out.append('  sleeves?: { L: ArtGrid; R: ArtGrid }; hood?: ArtGrid }')
    out.append('export interface PaletteSkin { id: string; name: string; pal: Record<string, string> }')
    out.append("export interface CostumeLayer extends ArtGrid { z: 'back' | 'body' | 'hands' | 'head' }")
    out.append('export interface Costume { id: string; name: string; pal: Record<string, string>; eyes: boolean; layers: CostumeLayer[] }')
    out.append('type RGB = [number, number, number];')
    out.append('export interface FxColours { dirt: RGB[]; spark: RGB[]; smoke: RGB[]; star: RGB; sweat: RGB; heal: RGB[] }')
    out.append('')
    for k, v in data.items():
        out.append('export const %s: %s = %s;' % (k, types[k], json.dumps(v, indent=1)))
        out.append('')
    with open(dst, 'w') as f:
        f.write('\n'.join(out))
    print('wrote', dst)


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
